import re
from typing import Any, Dict, List, Optional, Union


def flask_to_openapi_path(rule: str) -> str:
    """Converts Flask URL pattern like '/api/equipment/<int_or_str:id>'
    to OpenAPI pattern '/api/equipment/{id}'.
    """
    return re.sub(r"<(?:\w+:)?(\w+)>", r"{\1}", rule)


def extract_path_params(rule: str) -> List[Dict[str, Any]]:
    """Extracts path parameter schemas from a Flask route rule."""
    matches = re.findall(r"<(?:\w+:)?(\w+)>", rule)
    params = []
    for m in matches:
        params.append({
            "name": m,
            "in": "path",
            "required": True,
            "schema": {"type": "string"},
            "description": f"Unique identifier for {m}"
        })
    return params


def field_to_openapi(field: Any) -> Dict[str, Any]:
    """Converts a Marshmallow field instance to an OpenAPI 3.0 property schema."""
    field_cls_name = field.__class__.__name__

    type_mapping = {
        "String": {"type": "string"},
        "Str": {"type": "string"},
        "Integer": {"type": "integer"},
        "Int": {"type": "integer"},
        "Float": {"type": "number", "format": "float"},
        "Decimal": {"type": "number", "format": "double"},
        "Number": {"type": "number"},
        "Boolean": {"type": "boolean"},
        "Bool": {"type": "boolean"},
        "DateTime": {"type": "string", "format": "date-time"},
        "Date": {"type": "string", "format": "date"},
        "Time": {"type": "string"},
        "Email": {"type": "string", "format": "email"},
        "URL": {"type": "string", "format": "uri"},
        "Url": {"type": "string", "format": "uri"},
        "UUID": {"type": "string", "format": "uuid"},
        "Dict": {"type": "object"},
        "Raw": {"type": "object"},
        "Field": {"type": "string"},
    }

    schema = dict(type_mapping.get(field_cls_name, {"type": "string"}))

    # Read-only / Write-only
    if getattr(field, "dump_only", False):
        schema["readOnly"] = True
    if getattr(field, "load_only", False):
        schema["writeOnly"] = True

    # Description
    desc = getattr(field, "metadata", {}).get("description") or getattr(field, "doc", None)
    if desc:
        schema["description"] = str(desc)

    # Defaults
    default_val = getattr(field, "load_default", getattr(field, "default", None))
    if default_val is not None and not callable(default_val) and "missing" not in default_val.__class__.__name__.lower():
        schema["default"] = default_val

    # List fields
    if field_cls_name == "List" and hasattr(field, "inner"):
        schema["type"] = "array"
        schema["items"] = field_to_openapi(field.inner)

    # Nested fields
    if field_cls_name == "Nested" and hasattr(field, "schema"):
        schema = schema_to_openapi(field.schema)

    # Enums (OneOf validator)
    for validator in getattr(field, "validators", []):
        if validator.__class__.__name__ == "OneOf" and hasattr(validator, "choices"):
            schema["enum"] = list(validator.choices)

    return schema


def schema_to_openapi(schema_obj: Any) -> Dict[str, Any]:
    """Converts a Marshmallow Schema class or instance to an OpenAPI schema object."""
    if schema_obj is None:
        return {"type": "object"}

    schema_inst = schema_obj() if isinstance(schema_obj, type) else schema_obj
    fields = getattr(schema_inst, "fields", {}) or getattr(schema_inst, "_declared_fields", {})

    properties = {}
    required = []

    for name, field in fields.items():
        properties[name] = field_to_openapi(field)
        if getattr(field, "required", False) and not getattr(field, "dump_only", False):
            required.append(name)

    res = {
        "type": "object",
        "properties": properties,
    }
    if required:
        res["required"] = required
    return res


def generate_openapi_spec(
    factory: Any,
    title: str = "API Documentation",
    version: str = "1.0.0",
    description: str = "RESTful API generated by api-factory",
    servers: Optional[List[Dict[str, str]]] = None,
) -> Dict[str, Any]:
    """Generates an OpenAPI 3.0.3 specification dict from an ApiFactory instance."""
    spec = {
        "openapi": "3.0.3",
        "info": {
            "title": title,
            "version": version,
            "description": description,
        },
        "servers": servers or [{"url": "/"}],
        "tags": [],
        "paths": {},
        "components": {
            "schemas": {},
            "responses": {
                "NotFound": {
                    "description": "Entity not found",
                    "content": {
                        "application/json": {
                            "schema": {
                                "type": "object",
                                "properties": {
                                    "error": {"type": "string", "example": "Not Found"},
                                    "message": {"type": "string"}
                                }
                            }
                        }
                    }
                },
                "ValidationError": {
                    "description": "Validation error",
                    "content": {
                        "application/json": {
                            "schema": {
                                "type": "object",
                                "properties": {
                                    "error": {"type": "string", "example": "Validation Error"},
                                    "messages": {"type": "object"}
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    seen_tags = set()
    components = spec["components"]["schemas"]
    paths = spec["paths"]

    # Extract error schemas from factory initialization
    factory_error_schemas = dict(getattr(factory, "error_schemas", {}) or {})
    default_err_schema = getattr(factory, "error_schema", None) or factory_error_schemas.get("default")

    # Discover error schemas attached to Blueprint or App error handlers (handler.schema)
    target_apps = []
    if getattr(factory, "app", None):
        target_apps.append(factory.app)
    for res in getattr(factory, "resources", []):
        bp = getattr(res, "app_or_bp", None)
        if bp and bp not in target_apps:
            target_apps.append(bp)

    for target in target_apps:
        err_spec = getattr(target, "error_handler_spec", {})
        for bp_key, code_map in err_spec.items():
            if isinstance(code_map, dict):
                for sub_k, sub_v in code_map.items():
                    if callable(sub_v):
                        schema = getattr(sub_v, "schema", None) or getattr(sub_v, "_schema", None)
                        code = sub_k if isinstance(sub_k, int) else getattr(sub_k, "code", None)
                        if schema and code:
                            factory_error_schemas.setdefault(code, schema)
                    elif isinstance(sub_v, dict):
                        for exc_cls, handler in sub_v.items():
                            schema = getattr(handler, "schema", None) or getattr(handler, "_schema", None)
                            code = sub_k if isinstance(sub_k, int) else (getattr(exc_cls, "code", None) or getattr(sub_k, "code", None))
                            if schema and code:
                                factory_error_schemas.setdefault(code, schema)

    # Process default error schema
    if default_err_schema:
        d_dict = schema_to_openapi(default_err_schema)
        spec["components"]["schemas"]["ErrorResponse"] = d_dict
        spec["components"]["responses"]["DefaultError"] = {
            "description": "Standard API error response",
            "content": {"application/json": {"schema": {"$ref": "#/components/schemas/ErrorResponse"}}}
        }
        spec["components"]["responses"]["NotFound"]["content"]["application/json"]["schema"] = {"$ref": "#/components/schemas/ErrorResponse"}
        spec["components"]["responses"]["ValidationError"]["content"]["application/json"]["schema"] = {"$ref": "#/components/schemas/ErrorResponse"}

    # Process explicit error status codes (e.g. 400, 401, 403, 404, 422, 500)
    for code, err_schema in list(factory_error_schemas.items()):
        if str(code) == "default":
            continue
        code_str = str(code)
        c_name = f"Error_{code_str}"
        c_dict = schema_to_openapi(err_schema)
        spec["components"]["schemas"][c_name] = c_dict
        spec["components"]["responses"][f"Error{code_str}"] = {
            "description": f"HTTP {code_str} error response",
            "content": {"application/json": {"schema": {"$ref": f"#/components/schemas/{c_name}"}}}
        }
        if code_str == "400":
            spec["components"]["responses"]["ValidationError"] = {
                "description": "Validation error response",
                "content": {"application/json": {"schema": {"$ref": f"#/components/schemas/{c_name}"}}}
            }
        elif code_str == "404":
            spec["components"]["responses"]["NotFound"] = {
                "description": "Resource not found response",
                "content": {"application/json": {"schema": {"$ref": f"#/components/schemas/{c_name}"}}}
            }

    # Helper to append common errors (e.g. 500, 401) to operations if defined
    extra_error_refs = {}
    for code_val in (401, 403, 422, 500):
        code_str = str(code_val)
        if f"Error{code_str}" in spec["components"]["responses"]:
            extra_error_refs[code_str] = {"$ref": f"#/components/responses/Error{code_str}"}

    for resource in getattr(factory, "resources", []):
        model_name = resource.model.__name__ if hasattr(resource.model, "__name__") else "Resource"
        docs = getattr(resource, "docs", {})
        tag_name = docs.get("tag", model_name)
        tag_desc = docs.get("description", getattr(resource.model, "__doc__", "") or f"CRUD operations for {model_name}.")

        if tag_name not in seen_tags:
            tag_def = {"name": tag_name, "description": tag_desc}
            if docs.get("keywords"):
                tag_def["x-keywords"] = docs["keywords"]
            spec["tags"].append(tag_def)
            seen_tags.add(tag_name)

        # Generate component schemas for model
        schema_name = f"{model_name}"
        if schema_name not in components:
            components[schema_name] = schema_to_openapi(resource.schema)

        # Route 1: Collection Path (e.g. /api/equipment)
        coll_rule = resource.route_prefix
        open_coll_rule = flask_to_openapi_path(coll_rule)
        if open_coll_rule not in paths:
            paths[open_coll_rule] = {}

        path_item = paths[open_coll_rule]

        # GET collection
        methods = getattr(resource, "methods", ["GET", "POST", "PUT", "PATCH", "DELETE"])
        if "GET" in methods:
            query_params = []
            if getattr(resource, "paginate", True):
                query_params.extend([
                    {"name": "page", "in": "query", "schema": {"type": "integer", "default": 1}, "description": "Page number"},
                    {"name": "per_page", "in": "query", "schema": {"type": "integer", "default": getattr(resource, "page_size", 20), "maximum": getattr(resource, "max_page_size", 100)}, "description": "Items per page"},
                    {"name": "paginate", "in": "query", "schema": {"type": "boolean", "default": True}, "description": "Set to false to return all unpaginated items"},
                ])

            if getattr(resource, "search_fields", None):
                query_params.append({
                    "name": "q", "in": "query", "schema": {"type": "string"},
                    "description": f"Search terms across: {', '.join(resource.search_fields)}"
                })

            if getattr(resource, "sort_fields", None):
                sort_desc = f"Allowed sort fields: {', '.join(resource.sort_fields)}"
                if getattr(resource, "default_sort_field", None):
                    sort_desc += f" (default: {resource.default_sort_field})"
                query_params.extend([
                    {"name": "sort", "in": "query", "schema": {"type": "string", "enum": resource.sort_fields, "default": getattr(resource, "default_sort_field", None)}, "description": sort_desc},
                    {"name": "order", "in": "query", "schema": {"type": "string", "enum": ["asc", "desc"], "default": getattr(resource, "sort_order", "asc")}, "description": "Sort order direction"},
                ])

            for f_name in getattr(resource, "filter_fields", []):
                query_params.append({
                    "name": f_name, "in": "query", "schema": {"type": "string"}, "description": f"Filter by {f_name}"
                })

            query_params.extend([
                {"name": "include", "in": "query", "schema": {"type": "string"}, "description": "Comma-separated relationships to eager load (e.g. category,vendor)"},
                {"name": "exclude", "in": "query", "schema": {"type": "string"}, "description": "Comma-separated fields to exclude from response"},
                {"name": "export", "in": "query", "schema": {"type": "string", "enum": ["csv"]}, "description": "Export results as CSV"},
            ])

            # Path params if nested sub-resource
            nested_params = extract_path_params(coll_rule)
            all_coll_params = nested_params + query_params

            op_summary = docs.get("operations", {}).get("collection", {}).get("summary") or f"List {model_name} items"
            path_item["get"] = {
                "tags": [tag_name],
                "summary": op_summary,
                "description": f"Retrieve paginated and filtered list of {model_name} items.",
                "parameters": all_coll_params,
                "responses": {
                    "200": {
                        "description": "Successful collection response",
                        "content": {
                            "application/json": {
                                "schema": {
                                    "type": "object",
                                    "properties": {
                                        "items": {"type": "array", "items": {"$ref": f"#/components/schemas/{schema_name}"}},
                                        "page": {"type": "integer", "example": 1},
                                        "per_page": {"type": "integer", "example": 20},
                                        "total": {"type": "integer", "example": 100},
                                        "pages": {"type": "integer", "example": 5},
                                    }
                                }
                            }
                        }
                    }
                }
            }

        # POST collection
        if "POST" in methods:
            op_summary = docs.get("operations", {}).get("create", {}).get("summary") or f"Create {model_name}"
            path_item["post"] = {
                "tags": [tag_name],
                "summary": op_summary,
                "description": f"Create and persist a new {model_name} record.",
                "parameters": extract_path_params(coll_rule),
                "requestBody": {
                    "required": True,
                    "content": {
                        "application/json": {
                            "schema": {"$ref": f"#/components/schemas/{schema_name}"}
                        }
                    }
                },
                "responses": {
                    "201": {
                        "description": f"{model_name} created successfully",
                        "content": {
                            "application/json": {"schema": {"$ref": f"#/components/schemas/{schema_name}"}}
                        }
                    },
                    "400": {"$ref": "#/components/responses/ValidationError"}
                }
            }

        # Route 2: Item Path (e.g. /api/equipment/{id})
        item_pk_name = getattr(resource, "pk_name", "id")
        item_pk_type = getattr(resource, "pk_type", "int_or_str")
        item_rule = f"{resource.route_prefix.rstrip('/')}/<{item_pk_type}:{item_pk_name}>"
        open_item_rule = flask_to_openapi_path(item_rule)

        if open_item_rule not in paths:
            paths[open_item_rule] = {}

        item_path_item = paths[open_item_rule]
        item_params = extract_path_params(item_rule)

        # GET item
        if "GET" in methods:
            op_summary = docs.get("operations", {}).get("item", {}).get("summary") or f"Get {model_name} by ID"
            item_path_item["get"] = {
                "tags": [tag_name],
                "summary": op_summary,
                "description": f"Retrieve details for a single {model_name}.",
                "parameters": item_params,
                "responses": {
                    "200": {
                        "description": f"Single {model_name} details",
                        "content": {
                            "application/json": {"schema": {"$ref": f"#/components/schemas/{schema_name}"}}
                        }
                    },
                    "404": {"$ref": "#/components/responses/NotFound"}
                }
            }

        # PUT item
        if "PUT" in methods:
            op_summary = docs.get("operations", {}).get("update", {}).get("summary") or f"Update {model_name}"
            item_path_item["put"] = {
                "tags": [tag_name],
                "summary": op_summary,
                "description": f"Replace and update an existing {model_name}.",
                "parameters": item_params,
                "requestBody": {
                    "required": True,
                    "content": {
                        "application/json": {"schema": {"$ref": f"#/components/schemas/{schema_name}"}}
                    }
                },
                "responses": {
                    "200": {
                        "description": f"{model_name} updated successfully",
                        "content": {
                            "application/json": {"schema": {"$ref": f"#/components/schemas/{schema_name}"}}
                        }
                    },
                    "400": {"$ref": "#/components/responses/ValidationError"},
                    "404": {"$ref": "#/components/responses/NotFound"}
                }
            }

        # PATCH item
        if "PATCH" in methods:
            op_summary = docs.get("operations", {}).get("patch", {}).get("summary") or f"Partial update {model_name}"
            item_path_item["patch"] = {
                "tags": [tag_name],
                "summary": op_summary,
                "description": f"Partially update fields of an existing {model_name}.",
                "parameters": item_params,
                "requestBody": {
                    "required": True,
                    "content": {
                        "application/json": {"schema": {"$ref": f"#/components/schemas/{schema_name}"}}
                    }
                },
                "responses": {
                    "200": {
                        "description": f"{model_name} partially updated",
                        "content": {
                            "application/json": {"schema": {"$ref": f"#/components/schemas/{schema_name}"}}
                        }
                    },
                    "404": {"$ref": "#/components/responses/NotFound"}
                }
            }

        # DELETE item
        if "DELETE" in methods:
            op_summary = docs.get("operations", {}).get("delete", {}).get("summary") or f"Delete {model_name}"
            item_path_item["delete"] = {
                "tags": [tag_name],
                "summary": op_summary,
                "description": f"Delete a {model_name} record.",
                "parameters": item_params,
                "responses": {
                    "200": {
                        "description": f"{model_name} deleted successfully",
                        "content": {
                            "application/json": {
                                "schema": {
                                    "type": "object",
                                    "properties": {"message": {"type": "string", "example": f"{model_name} deleted successfully."}}
                                }
                            }
                        }
                    },
                    "404": {"$ref": "#/components/responses/NotFound"}
                }
            }

        # Document Custom Actions registered on resource
        for action in getattr(resource, "actions", []):
            rule = action.get("rule", "")
            open_action_rule = flask_to_openapi_path(rule)
            if open_action_rule not in paths:
                paths[open_action_rule] = {}

            action_path_item = paths[open_action_rule]
            act_docs = action.get("docs", {})
            act_summary = act_docs.get("summary") if isinstance(act_docs, dict) else (str(act_docs) if act_docs else None)
            act_desc = act_docs.get("description", "") if isinstance(act_docs, dict) else ""
            act_schema = action.get("schema")

            action_params = extract_path_params(rule)

            for method in action.get("methods", ["POST"]):
                m_lower = method.lower()
                op_data = {
                    "tags": [tag_name],
                    "summary": act_summary or f"{method} {open_action_rule.split('/')[-1]}",
                    "description": act_desc or f"Custom action {open_action_rule}",
                    "parameters": action_params,
                    "responses": {
                        "200": {"description": "Action executed successfully"},
                        "201": {"description": "Resource created via action"},
                        "400": {"$ref": "#/components/responses/ValidationError"},
                        "404": {"$ref": "#/components/responses/NotFound"},
                    }
                }

                if act_schema and method in ("POST", "PUT", "PATCH"):
                    action_schema_name = f"{model_name}_{open_action_rule.split('/')[-1].capitalize()}Payload"
                    if action_schema_name not in components:
                        components[action_schema_name] = schema_to_openapi(act_schema)
                    op_data["requestBody"] = {
                        "required": True,
                        "content": {
                            "application/json": {
                                "schema": {"$ref": f"#/components/schemas/{action_schema_name}"}
                            }
                        }
                    }

                action_path_item[m_lower] = op_data

    # Document Standalone Custom Views registered on factory
    for custom in getattr(factory, "custom_views", []):
        rule = custom.get("rule", "")
        open_rule = flask_to_openapi_path(rule)
        if open_rule not in paths:
            paths[open_rule] = {}

        p_item = paths[open_rule]
        c_docs = custom.get("docs", {})
        c_tag = c_docs.get("tag", "Custom Views") if isinstance(c_docs, dict) else "Custom Views"
        c_summary = c_docs.get("summary") if isinstance(c_docs, dict) else (str(c_docs) if c_docs else None)
        c_desc = c_docs.get("description", "") if isinstance(c_docs, dict) else ""
        c_schema = custom.get("schema")

        if c_tag not in seen_tags:
            spec["tags"].append({"name": c_tag, "description": "Standalone custom views and actions"})
            seen_tags.add(c_tag)

        for method in custom.get("methods", ["GET"]):
            m_lower = method.lower()
            op = {
                "tags": [c_tag],
                "summary": c_summary or f"{method} {open_rule}",
                "description": c_desc,
                "parameters": extract_path_params(rule),
                "responses": {
                    "200": {"description": "Success"}
                }
            }
            if c_schema and method in ("POST", "PUT", "PATCH"):
                c_schema_name = f"Custom_{open_rule.strip('/').replace('/', '_')}_Payload"
                if c_schema_name not in components:
                    components[c_schema_name] = schema_to_openapi(c_schema)
                op["requestBody"] = {
                    "required": True,
                    "content": {"application/json": {"schema": {"$ref": f"#/components/schemas/{c_schema_name}"}}}
                }
            p_item[m_lower] = op

    # Ensure extra error responses (e.g. 500, 401, 403, 422) appear in all operations
    if extra_error_refs:
        for path_key, path_obj in paths.items():
            for method_key, op_obj in path_obj.items():
                if isinstance(op_obj, dict) and "responses" in op_obj:
                    for err_code, ref_data in extra_error_refs.items():
                        if err_code not in op_obj["responses"]:
                            op_obj["responses"][err_code] = ref_data

    return spec


def get_swagger_ui_html(openapi_url: str, title: str = "API Documentation") -> str:
    """Renders HTML page for Swagger UI using jsDelivr CDN."""
    return f"""<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8"/>
  <title>{title} - Swagger UI</title>
  <link rel="stylesheet" type="text/css" href="https://cdn.jsdelivr.net/npm/swagger-ui-dist@5/swagger-ui.css" />
  <style>
    body {{ margin: 0; background: #fafafa; }}
    .swagger-ui .topbar {{ display: none; }}
  </style>
</head>
<body>
  <div id="swagger-ui"></div>
  <script src="https://cdn.jsdelivr.net/npm/swagger-ui-dist@5/swagger-ui-bundle.js"></script>
  <script>
    window.onload = function() {{
      SwaggerUIBundle({{
        url: "{openapi_url}",
        dom_id: '#swagger-ui',
        deepLinking: true,
        presets: [
          SwaggerUIBundle.presets.apis,
          SwaggerUIBundle.SwaggerUIStandalonePreset
        ],
        layout: "BaseLayout"
      }});
    }};
  </script>
</body>
</html>
"""


